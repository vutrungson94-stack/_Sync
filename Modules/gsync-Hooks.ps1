#Requires -Version 5.1


# The shared bootstrap makes the logger and the locale resolver available.
. (Join-Path $PSScriptRoot 'ModuleBootstrap.ps1')
function New-GSyncHookLauncher {
    <#
    .SYNOPSIS
        Produces the POSIX sh launcher installed as .git/hooks/<type>.
    .DESCRIPTION
        git runs a hook through the shell named in its shebang. A pure
        PowerShell hook body with a '#!/usr/bin/env pwsh' shebang broke on
        Windows PowerShell: Set-Content -Encoding UTF8 wrote a BOM, the BOM
        broke the shebang, git fell back to sh.exe, and the PowerShell body
        was not valid sh - every commit was blocked with a syntax error.
        The launcher is plain sh (works with git-for-Windows' bundled sh) and
        it locates pwsh or powershell itself. The PowerShell body lives in a
        companion file so the launcher stays valid sh.
    #>
    [CmdletBinding()]
    param([string]$HookType)

Set-StrictMode -Version 1.0
    $template = @'
#!/bin/sh
# gsync <HOOKTYPE> hook - generated by gsync. Do not edit; reinstall instead.
repo_root="$(git rev-parse --show-toplevel 2>/dev/null)"
if [ -z "$repo_root" ]; then exit 0; fi
# The tooling can live inside the repo or in a sibling folder next to it.
# Both layouts are checked so hooks installed by either stay effective.
gsync_dir="$repo_root/_Sync"
if [ ! -f "$gsync_dir/Modules/gsync-Hooks.ps1" ]; then
  gsync_dir="$(dirname "$repo_root")/_Sync"
fi
if [ ! -f "$gsync_dir/Modules/gsync-Hooks.ps1" ]; then exit 0; fi
if command -v pwsh >/dev/null 2>&1; then
  exec pwsh -NoProfile -NonInteractive -File "$0.gsync.ps1" "$@"
fi
if command -v powershell >/dev/null 2>&1; then
  exec powershell -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "$0.gsync.ps1" "$@"
fi
exit 0
'@
    return $template.Replace('__HOOKTYPE__', $HookType)
}

function New-GSyncHookScript {
    <#
    .SYNOPSIS
        Produces the PowerShell body that runs the hook handler.
    #>
    [CmdletBinding()]
    param([string]$HookType)
    $template = @'
#Requires -Version 5.1
$ErrorActionPreference = 'Continue'
$repoRoot = & git rev-parse --show-toplevel 2>$null
if (-not $repoRoot) { exit 0 }
# Same two layouts the sh launcher checks: _Sync inside the repo, or as a
# sibling folder next to it.
$syncRoot = $null
$syncCandidates = @(
    (Join-Path $repoRoot "_Sync"),
    (Join-Path (Split-Path -Parent $repoRoot) "_Sync")
)
foreach ($cand in $syncCandidates) {
    if (Test-Path (Join-Path $cand "Modules\gsync-Hooks.ps1")) { $syncRoot = $cand; break }
}
if (-not $syncRoot) { exit 0 }
$gsyncDir = Join-Path $syncRoot "Modules"
$gsyncHooks = Join-Path $gsyncDir "gsync-Hooks.ps1"
if (-not (Test-Path $gsyncHooks)) { exit 0 }
# The handler needs the logger, the secret scanner and the alerting bridge.
# Without them the hook silently degraded to a no-op.
foreach ($dep in @('Logging.psm1','Security.psm1','Alerting.psm1','EventBus.psm1')) {
    $depPath = Join-Path $gsyncDir $dep
    if (Test-Path $depPath) { Import-Module $depPath -Force -Global -ErrorAction SilentlyContinue }
}
. $gsyncHooks
$confPath = Join-Path $syncRoot "gsync.config.json"
$cfg = if (Test-Path $confPath) { Get-Content $confPath -Raw | ConvertFrom-Json } else { @{} }
$ok = Invoke-GSyncHook -HookType '__HOOKTYPE__' -Config $cfg
exit ( -not ([bool]$ok) )
'@
    return $template.Replace('__HOOKTYPE__', $HookType)
}

function Write-GSyncHookFile {
    <#
    .SYNOPSIS
        Writes a hook file WITHOUT a UTF-8 BOM.
    .DESCRIPTION
        A BOM in a '#!' file breaks the shebang on every platform. The file
        is written as raw UTF-8 with no BOM.
    #>
    [CmdletBinding()]
    param([string]$Path, [string]$Content)
    [System.IO.File]::WriteAllText($Path, $Content, (New-Object System.Text.UTF8Encoding($false)))
}

function Install-GSyncHooks {
    [CmdletBinding()]
    param([string]$RepoPath, [string[]]$HookTypes, [switch]$Force)
    if (-not $HookTypes) { $HookTypes = @('pre-commit','pre-push','post-commit') }
    $hooksDir = Join-Path (Join-Path $RepoPath ".git") "hooks"
    if (-not (Test-Path $hooksDir)) { Write-Warning (Get-LocaleMessage -Key 'gsync.msg.hook.noHooksDir' -MessageArgs @($RepoPath)); return }
    foreach ($hook in $HookTypes) {
        $hookPath = Join-Path $hooksDir $hook
        $bodyPath = "$hookPath.gsync.ps1"
        if ((Test-Path $hookPath) -and -not $Force) { Write-Warning (Get-LocaleMessage -Key 'gsync.msg.hook.exists' -MessageArgs @($hook)); continue }
        Write-GSyncHookFile -Path $hookPath -Content (New-GSyncHookLauncher -HookType $hook)
        Write-GSyncHookFile -Path $bodyPath -Content (New-GSyncHookScript -HookType $hook)
        # Make executable on POSIX so git can run the hook directly (no pwsh prefix needed)
        if ([System.Environment]::OSVersion.Platform -ne [System.PlatformID]::Win32NT) {
            try { chmod +x $hookPath 2>$null } catch { }
        }
        Write-Host (Get-LocaleMessage -Key 'gsync.msg.hook.installed' -MessageArgs @($hook)) -ForegroundColor Green
    }
}
function Remove-GSyncHooks {
    param([string]$RepoPath, [string[]]$HookTypes)
    if (-not $HookTypes) { $HookTypes = @('pre-commit','pre-push','post-commit') }
    $hooksDir = Join-Path (Join-Path $RepoPath ".git") "hooks"
    if (-not (Test-Path $hooksDir)) { return }
    foreach ($hook in $HookTypes) {
        $hp = Join-Path $hooksDir $hook
        if (Test-Path $hp) { Remove-Item -Path $hp -Force; Write-Host (Get-LocaleMessage -Key 'gsync.msg.hook.removed' -MessageArgs @($hook)) -ForegroundColor Yellow }
        $bodyPath = "$hp.gsync.ps1"
        if (Test-Path $bodyPath) { Remove-Item -Path $bodyPath -Force }
    }
}
function Test-GSyncHooks {
    param([string]$RepoPath)
    $hooksDir = Join-Path (Join-Path $RepoPath ".git") "hooks"
    # PowerShell unrolls an empty array to $null, so the caller got $null
    # instead of an array. The comma keeps it an array.
    if (-not (Test-Path $hooksDir)) { return ,@() }
    $installed = @(Get-ChildItem $hooksDir | Where-Object { $_.Name -in @('pre-commit','pre-push','post-commit') })
    return ,@($installed | ForEach-Object { $_.Name })
}
function Invoke-GSyncHook {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$HookType,
        $Config = $null,
        [hashtable]$Context = $null
    )
    # Single source of truth for hook execution:
    #   1) Built-in handler scripts (gsync-pre-commit.ps1, ...)
    #   2) User-configured hook scripts (config: hooks.preCommit / prePush / ...)
    $ok = $true
    $handlerRan = $false

    $hookScript = Join-Path $PSScriptRoot "gsync-${HookType}.ps1"
    if (Test-Path $hookScript) {
        $handlerRan = $true
        # The handler signals a block by returning $false. The previous
        # implementation used "if (-not $?)", but $? reports whether the
        # last command ERRORED, not what it returned - a handler that
        # returned $false left $? as $true, so the secret gate never
        # blocked a commit. The verdict is the handler's return value.
        $handlerOutput = @(& $hookScript -Config $Config)
        $verdict = $null
        foreach ($item in $handlerOutput) {
            if ($item -is [bool]) { $verdict = $item }
        }
        if ($null -ne $verdict -and -not $verdict) { $ok = $false }
    }

    # Map CLI-style hook names to config keys (pre-commit -> preCommit)
    $keyMap = @{ 'pre-commit' = 'preCommit'; 'post-commit' = 'postCommit'; 'pre-push' = 'prePush'; 'post-push' = 'postPush' }
    $cfgKey = if ($keyMap.ContainsKey($HookType)) { $keyMap[$HookType] } else { $HookType }
    if ($Config -and $Config.PSObject.Properties.Name -contains 'hooks' -and $Config.hooks -and $Config.hooks.PSObject.Properties.Name -contains $cfgKey -and $Config.hooks.$cfgKey) {
        $handlerRan = $true
        foreach ($scriptPath in @($Config.hooks.$cfgKey)) {
            if (-not (Test-Path $scriptPath)) {
                Write-Warn (Get-LocaleMessage -Key 'gsync.msg.hook.notFound' -MessageArgs @([string]$scriptPath))
                $ok = $false
                continue
            }
            try {
                $prev = Get-Location
                if ($Context -and $Context.ScriptRoot) { Set-Location $Context.ScriptRoot }
                . $scriptPath
                Set-Location $prev
            } catch {
                Write-GSyncError "Hook '$scriptPath' failed: $_"
                $ok = $false
            }
        }
    }

    if (-not $handlerRan) {
        Write-Debug (Get-LocaleMessage -Key 'gsync.msg.hook.noHandler' -MessageArgs @($HookType))
    }
    return $ok
}

